// Ảnh chụp thêm: panel cây thu gọn, tab nhân sự + mở chi tiết (nút đóng), đóng chi tiết.
import { chromium } from 'playwright';
const root = '/home/claude/kit/prototype-kit-CATALOG-1012m/prototypes/cam-nang-phan-quyen/';
const file = process.argv[2] || 'tra-cuu-cam-nang-v2.html';
const out = '/home/claude/work/round/agents/v2/' + file;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--allow-file-access-from-files'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.route(/^https?:/, r => r.abort());
const errs = []; p.on('pageerror', e => errs.push(String(e).slice(0, 300)));
const W = ms => p.waitForTimeout(ms || 400);
await p.goto('file://' + root + file + '?categoryId=general&itemNumber=1.1'); await p.waitForTimeout(1500);
await p.locator('#tree-collapse-toggle').click(); await W(900);
await p.screenshot({ path: out + '.collapsed.png' });
await p.locator('#lookup-tree-reopen').click(); await W(900);
await p.click('.page-tab-zone .tab:nth-child(2)'); await W(800);
await p.locator('#identity-search-person').click(); await W(400);
await p.locator('.cdk-overlay-pane .sd-dropdown-item, #identity-search-person .single-filter-option').first().click(); await W(800);
await p.locator('.workitem-link').first().click(); await W(900);
console.log('detail open in identity', await p.locator('.lookup-shell').evaluate(e => e.className));
console.log('close visible', await p.locator('.inline-detail-close').isVisible());
await p.screenshot({ path: out + '.identity-detail.png' });
await p.locator('.inline-detail-close').click(); await W(600);
console.log('after close', await p.locator('#inline-detail-panel').evaluate(e => e.className));
await b.close();
console.log(errs.length ? 'JS ERRORS:\n  ' + errs.join('\n  ') : 'Không lỗi JS.');
